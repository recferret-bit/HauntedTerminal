// Canonical Rust `DesktopBridge` (`src-tauri/src/steam.rs`) template emitter for `scripts/desktop/generate-tauri-steam.mjs`.

function renderSteamTypesRs() {
  return [
    'use crate::achievements_manifest::{is_known_api_name, DEFAULT_STEAM_APP_ID};',
    'use serde::{Deserialize, Serialize};',
    'use std::collections::BTreeSet;',
    'use std::fs;',
    'use std::path::{Path, PathBuf};',
    'use std::process::Command;',
    'use std::sync::{Arc, Mutex};',
    '',
    'const MAX_SAVE_BUNDLE_BYTES: usize = 256_000;',
    '// Names used before the project was renamed to Out Of Credits: still read, never written.',
    'const LEGACY_SAVE_FILE: &str = "haunted-terminal-save.json";',
    'const LEGACY_SAVE_FORMAT: &str = "haunted-terminal-save";',
    'const ALLOWED_EXPORT_FILES: &[&str] = &["out-of-credits-save.json", "out-of-credits-steam-waitlist.json"];',
    '#[cfg(feature = "steam")]',
    'const STEAM_STORE_PREFIX: &str = "https://store.steampowered.com/app/";',
    '',
    '#[derive(Debug, Clone, Serialize, Deserialize, Default)]',
    'pub struct LocalAchievementLedger {',
    '    pub unlocked_api_names: BTreeSet<String>,',
    '}',
    '',
    '#[derive(Debug, Clone, Serialize)]',
    '#[serde(rename_all = "camelCase")]',
    'pub struct SteamStatusReply {',
    '    pub tauri: bool,',
    '    pub steam_enabled: bool,',
    '    pub steam_running: bool,',
    '    pub steam_deck: bool,',
    '    pub app_id: Option<u32>,',
    '}',
    '',
    '#[derive(Debug, Clone, Serialize)]',
    '#[serde(rename_all = "camelCase")]',
    'pub struct UnlockReply {',
    '    pub unlocked: bool,',
    '    pub steam_pushed: bool,',
    '}',
    '',
    '#[derive(Debug, Clone, Serialize)]',
    '#[serde(rename_all = "camelCase")]',
    'pub struct SyncReply {',
    '    pub synced: usize,',
    '    pub steam_running: bool,',
    '}',
    '',
    'pub struct DesktopBridge {',
    '    ledger_path: PathBuf,',
    '    save_bundle_path: PathBuf,',
    '    download_dir: PathBuf,',
    '    ledger: Arc<Mutex<LocalAchievementLedger>>,',
    '    app_id: Option<u32>,',
    '    #[cfg(feature = "steam")]',
    '    steam_client: Option<steamworks::Client>,',
    '    #[cfg(feature = "steam")]',
    '    _stats_cb: Option<steamworks::CallbackHandle>,',
    '}',
    '',
    'pub fn is_allowed_external_url(url: &str) -> bool {',
    '    if url.is_empty() || url.len() > 512 || url.contains("..") || url.to_ascii_lowercase().contains("%2e") {',
    '        return false;',
    '    }',
    '    if url.chars().any(|c| c.is_control() || c.is_whitespace() || matches!(c, \'"\' | \'\\\'\' | \'<\' | \'>\' | \'\\\\\' | \'`\')) {',
    '        return false;',
    '    }',
    '    let Some(rest) = url.strip_prefix("https://") else { return false };',
    '    if rest.contains("//") {',
    '        return false;',
    '    }',
    '    if let Some(after_app) = rest.strip_prefix("store.steampowered.com/app/") {',
    '        let digits = after_app.bytes().take_while(|b| b.is_ascii_digit()).count();',
    '        return digits > 0 && matches!(after_app.as_bytes().get(digits), None | Some(b\'/\') | Some(b\'?\') | Some(b\'#\'));',
    '    }',
    '    if let Some(after_gh) = rest.strip_prefix("github.com/recferret-bit/OutOfCredits").or_else(|| rest.strip_prefix("github.com/recferret-bit/HauntedTerminal")) {',
    '        return matches!(after_gh.as_bytes().first(), None | Some(b\'/\') | Some(b\'?\') | Some(b\'#\'));',
    '    }',
    '    false',
    '}',
    '',
    'fn is_save_format(parsed: &serde_json::Value) -> bool {',
    '    matches!(parsed.get("format").and_then(|v| v.as_str()), Some("out-of-credits-save") | Some(LEGACY_SAVE_FORMAT))',
    '}',
    '',
    'fn extract_save_bundle_keys(bundle_json: &str) -> Vec<String> {',
    '    let Ok(parsed) = serde_json::from_str::<serde_json::Value>(bundle_json) else { return Vec::new() };',
    '    if !is_save_format(&parsed) {',
    '        return Vec::new();',
    '    }',
    '    parsed.pointer("/achievements/unlocked")',
    '        .and_then(|v| v.as_object())',
    '        .map(|m| {',
    '            m.values()',
    '                .filter_map(|v| v.get("steamApiName").and_then(|k| k.as_str()))',
    '                .filter(|k| is_known_api_name(k))',
    '                .map(String::from)',
    '                .collect()',
    '        })',
    '        .unwrap_or_default()',
    '}',
    '',
    'fn unique_download_path(dir: &Path, filename: &str) -> PathBuf {',
    '    let first = dir.join(filename);',
    '    if !first.exists() {',
    '        return first;',
    '    }',
    '    let stem = filename.strip_suffix(".json").unwrap_or(filename);',
    '    for idx in 2..=999 {',
    '        let candidate = dir.join(format!("{}-{}.json", stem, idx));',
    '        if !candidate.exists() {',
    '            return candidate;',
    '        }',
    '    }',
    '    first',
    '}',
    '',
    'fn atomic_write(dest: &Path, content: &str) -> Result<(), String> {',
    '    let tmp = dest.with_extension("json.tmp");',
    '    if fs::write(&tmp, content).is_ok() && fs::rename(&tmp, dest).is_ok() {',
    '        return Ok(());',
    '    }',
    '    fs::write(dest, content).map_err(|e| format!("Failed writing {}: {}", dest.display(), e))',
    '}',
  ].join('\n');
}

function renderSteamBridgeInitRs() {
  return [
    '#[cfg(feature = "steam")]',
    'fn replay_arc_ledger(client: &steamworks::Client, ledger: &Arc<Mutex<LocalAchievementLedger>>) -> bool {',
    '    let Ok(guard) = ledger.lock() else { return false };',
    '    if guard.unlocked_api_names.is_empty() {',
    '        return true;',
    '    }',
    '    let stats = client.user_stats();',
    '    let mut any_ok = false;',
    '    let mut any_failed = false;',
    '    for key in &guard.unlocked_api_names {',
    '        if stats.achievement(key).set().is_ok() {',
    '            any_ok = true;',
    '        } else {',
    '            any_failed = true;',
    '        }',
    '    }',
    '    if any_ok {',
    '        let _ = stats.store_stats();',
    '    }',
    '    if any_failed {',
    '        stats.request_current_stats();',
    '    }',
    '    any_ok && !any_failed',
    '}',
    '',
    'impl DesktopBridge {',
    '    pub fn init(app_data_dir: PathBuf) -> Self {',
    '        let dl = app_data_dir.clone();',
    '        Self::with_dirs(app_data_dir, dl)',
    '    }',
    '',
    '    pub fn with_dirs(app_data_dir: PathBuf, download_dir: PathBuf) -> Self {',
    '        let _ = fs::create_dir_all(&app_data_dir);',
    '        let ledger_path = app_data_dir.join("achievements-ledger.json");',
    '        let save_bundle_path = app_data_dir.join("out-of-credits-save.json");',
    '        let legacy_save_path = app_data_dir.join(LEGACY_SAVE_FILE);',
    '        if !save_bundle_path.exists() && legacy_save_path.exists() {',
    '            let _ = fs::copy(&legacy_save_path, &save_bundle_path);',
    '        }',
    '        let mut initial_ledger = fs::read_to_string(&ledger_path)',
    '            .ok()',
    '            .and_then(|s| serde_json::from_str::<LocalAchievementLedger>(&s).ok())',
    '            .unwrap_or_default();',
    '        if let Ok(raw_save) = fs::read_to_string(&save_bundle_path) {',
    '            if !raw_save.is_empty() && raw_save.len() <= MAX_SAVE_BUNDLE_BYTES {',
    '                let mut seeded = false;',
    '                for key in extract_save_bundle_keys(&raw_save) {',
    '                    if initial_ledger.unlocked_api_names.insert(key) { seeded = true; }',
    '                }',
    '                if seeded {',
    '                    if let Ok(json) = serde_json::to_string_pretty(&initial_ledger) {',
    '                        let _ = atomic_write(&ledger_path, &json);',
    '                    }',
    '                }',
    '            }',
    '        }',
    '        let ledger = Arc::new(Mutex::new(initial_ledger));',
    '        let env_app_id = std::env::var("STEAM_APP_ID").ok().and_then(|v| v.parse::<u32>().ok());',
    '        let app_id = env_app_id.or(DEFAULT_STEAM_APP_ID);',
    '',
    '        #[cfg(feature = "steam")]',
    '        let (steam_client, _stats_cb) = {',
    '            let init_res = match app_id {',
    '                Some(id) => steamworks::Client::init_app(id),',
    '                None => steamworks::Client::init(),',
    '            };',
    '            match init_res {',
    '                Ok((client, single)) => {',
    '                    let cb_client = client.clone();',
    '                    let cb_ledger = Arc::clone(&ledger);',
    '                    let handle = client.register_callback(move |val: steamworks::UserStatsReceived| {',
    '                        if val.result.is_ok() {',
    '                            let _ = replay_arc_ledger(&cb_client, &cb_ledger);',
    '                        }',
    '                    });',
    '                    client.user_stats().request_current_stats();',
    '                    std::thread::spawn(move || loop {',
    '                        single.run_callbacks();',
    '                        std::thread::sleep(std::time::Duration::from_millis(60));',
    '                    });',
    '                    (Some(client), Some(handle))',
    '                }',
    '                Err(_) => (None, None),',
    '            }',
    '        };',
    '',
    '        Self {',
    '            ledger_path,',
    '            save_bundle_path,',
    '            download_dir,',
    '            ledger,',
    '            app_id,',
    '            #[cfg(feature = "steam")]',
    '            steam_client,',
    '            #[cfg(feature = "steam")]',
    '            _stats_cb,',
    '        }',
    '    }',
    '',
    '    fn persist_ledger(&self, guard: &LocalAchievementLedger) {',
    '        if let Ok(json) = serde_json::to_string_pretty(guard) {',
    '            let _ = atomic_write(&self.ledger_path, &json);',
    '        }',
    '    }',
    '',
    '    fn push_one_to_steam(&self, _api_name: &str) -> bool {',
    '        #[cfg(feature = "steam")]',
    '        if let Some(client) = &self.steam_client {',
    '            let stats = client.user_stats();',
    '            if stats.achievement(_api_name).set().is_ok() {',
    '                return stats.store_stats().is_ok();',
    '            }',
    '            stats.request_current_stats();',
    '        }',
    '        false',
    '    }',
    '',
    '    fn replay_ledger_to_steam(&self) {',
    '        #[cfg(feature = "steam")]',
    '        if let Some(client) = &self.steam_client {',
    '            let _ = replay_arc_ledger(client, &self.ledger);',
    '        }',
    '    }',
  ].join('\n');
}

function renderSteamBridgeAchOpsRs() {
  return [
    '    pub fn status(&self) -> SteamStatusReply {',
    '        #[cfg(feature = "steam")]',
    '        let (running, deck) = match &self.steam_client {',
    '            Some(c) => (true, c.utils().is_steam_running_on_steam_deck()),',
    '            None => (false, false),',
    '        };',
    '        #[cfg(not(feature = "steam"))]',
    '        let (running, deck) = (false, false);',
    '        SteamStatusReply { tauri: true, steam_enabled: cfg!(feature = "steam"), steam_running: running, steam_deck: deck, app_id: self.app_id }',
    '    }',
    '',
    '    pub fn unlock(&self, api_name: &str) -> Result<UnlockReply, String> {',
    '        if !is_known_api_name(api_name) { return Err(format!("Unknown achievement API key: {}", api_name)); }',
    '        let mut guard = self.ledger.lock().map_err(|_| "Ledger mutex poisoned".to_string())?;',
    '        if guard.unlocked_api_names.insert(api_name.to_string()) { self.persist_ledger(&guard); }',
    '        drop(guard);',
    '        Ok(UnlockReply { unlocked: true, steam_pushed: self.push_one_to_steam(api_name) })',
    '    }',
    '',
    '    pub fn sync_many(&self, api_names: &[String]) -> Result<SyncReply, String> {',
    '        let mut guard = self.ledger.lock().map_err(|_| "Ledger mutex poisoned".to_string())?;',
    '        let mut valid_count = 0usize;',
    '        for key in api_names {',
    '            if is_known_api_name(key) { guard.unlocked_api_names.insert(key.clone()); valid_count += 1; }',
    '        }',
    '        self.persist_ledger(&guard);',
    '        drop(guard);',
    '        self.replay_ledger_to_steam();',
    '        Ok(SyncReply { synced: valid_count, steam_running: self.status().steam_running })',
    '    }',
    '',
    '    pub fn clear(&self, api_name: &str) -> Result<bool, String> {',
    '        if !is_known_api_name(api_name) { return Err(format!("Unknown achievement API key: {}", api_name)); }',
    '        let mut guard = self.ledger.lock().map_err(|_| "Ledger mutex poisoned".to_string())?;',
    '        guard.unlocked_api_names.remove(api_name);',
    '        self.persist_ledger(&guard);',
    '        #[cfg(feature = "steam")]',
    '        if let Some(client) = &self.steam_client {',
    '            let stats = client.user_stats();',
    '            let _ = stats.achievement(api_name).clear();',
    '            let _ = stats.store_stats();',
    '        }',
    '        Ok(true)',
    '    }',
  ].join('\n');
}

function renderSteamBridgeSaveAndShellOpsRs() {
  return [
    '    pub fn read_save_bundle(&self) -> Option<String> {',
    '        let raw = fs::read_to_string(&self.save_bundle_path).ok()?;',
    '        (!raw.is_empty() && raw.len() <= MAX_SAVE_BUNDLE_BYTES).then_some(raw)',
    '    }',
    '',
    '    pub fn write_save_bundle(&self, bundle_json: &str) -> Result<bool, String> {',
    '        if bundle_json.is_empty() || bundle_json.len() > MAX_SAVE_BUNDLE_BYTES {',
    '            return Err("Save bundle is empty or exceeds 256 KB".to_string());',
    '        }',
    '        let parsed: serde_json::Value = serde_json::from_str(bundle_json)',
    '            .map_err(|_| "Save bundle is not valid JSON".to_string())?;',
    '        if !is_save_format(&parsed) {',
    '            return Err("Invalid save bundle format header".to_string());',
    '        }',
    '        atomic_write(&self.save_bundle_path, bundle_json)?;',
    '        let keys = extract_save_bundle_keys(bundle_json);',
    '        if !keys.is_empty() { let _ = self.sync_many(&keys); }',
    '        Ok(true)',
    '    }',
    '',
    '    pub fn export_json_file(&self, filename: &str, json_content: &str) -> Result<String, String> {',
    '        if !ALLOWED_EXPORT_FILES.contains(&filename) {',
    '            return Err(format!("Blocked non-whitelisted export filename: {}", filename));',
    '        }',
    '        if json_content.is_empty() || json_content.len() > MAX_SAVE_BUNDLE_BYTES {',
    '            return Err("Export payload is empty or exceeds 256 KB".to_string());',
    '        }',
    '        serde_json::from_str::<serde_json::Value>(json_content)',
    '            .map_err(|_| "Export payload is not valid JSON".to_string())?;',
    '        if filename == "out-of-credits-save.json" {',
    '            self.write_save_bundle(json_content)?;',
    '        }',
    '        let _ = fs::create_dir_all(&self.download_dir);',
    '        let dest = unique_download_path(&self.download_dir, filename);',
    '        atomic_write(&dest, json_content)?;',
    '        Ok(dest.to_string_lossy().into_owned())',
    '    }',
    '',
    '    pub fn open_external_url(&self, url: &str) -> Result<bool, String> {',
    '        if !is_allowed_external_url(url) { return Err("Blocked non-whitelisted external URL".to_string()); }',
    '        #[cfg(feature = "steam")]',
    '        if url.starts_with(STEAM_STORE_PREFIX) {',
    '            if let Some(client) = &self.steam_client {',
    '                client.friends().activate_game_overlay_to_web_page(url);',
    '                return Ok(true);',
    '            }',
    '        }',
    '        #[cfg(target_os = "macos")]',
    '        let spawned = Command::new("open").arg(url).spawn();',
    '        #[cfg(target_os = "windows")]',
    '        let spawned = Command::new("rundll32").args(["url.dll,FileProtocolHandler", url]).spawn();',
    '        #[cfg(all(unix, not(target_os = "macos")))]',
    '        let spawned = Command::new("xdg-open").arg(url).spawn();',
    '        spawned.map(|_| true).map_err(|e| format!("Failed opening external URL: {}", e))',
    '    }',
    '',
    '    pub fn show_floating_keyboard(&self, _x: i32, _y: i32, _width: i32, _height: i32) -> bool {',
    '        #[cfg(feature = "steam")]',
    '        if let Some(client) = &self.steam_client {',
    '            if client.utils().is_steam_running_on_steam_deck() {',
    '                return client.utils().show_floating_gamepad_text_input(steamworks::FloatingGamepadTextInputMode::SingleLine, _x, _y, _width, _height, || {});',
    '            }',
    '        }',
    '        false',
    '    }',
    '}',
    '',
  ].join('\n');
}

