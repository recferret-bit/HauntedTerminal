// Reads comix/<slug>/ from disk and renders src/cinematic/generated/catalog-data.ts.
// Shared by `generate-comix.mjs` (CLI) and `/comix-editor`'s dev API so both compile identically.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { etagOf, etagOfFile } from './chapter-compile.mjs';
import { projectRoot } from './load.mjs';

export { etagOf, etagOfFile };

export const comixDir = resolve(projectRoot, 'comix');
export const comixCatalogFile = resolve(projectRoot, 'src/cinematic/generated/catalog-data.ts');

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));

export function listComixIds() {
  if (!existsSync(comixDir)) return [];
  return readdirSync(comixDir)
    .filter((d) => statSync(resolve(comixDir, d)).isDirectory() && existsSync(resolve(comixDir, d, 'comix.manifest.json')))
    .sort();
}

/**
 * One comix sequence as the editor and compiler see it. Paths are relative to `comix/<slug>/`.
 * `pages[i].path` is `manifest.pages[i].specPath`. `etags` hashes `comix.manifest.json` + every page spec.
 */
export function readComix(slug) {
  const dir = resolve(comixDir, slug);
  const manifestPath = resolve(dir, 'comix.manifest.json');
  const manifest = readJson(manifestPath);
  const pages = [];
  for (const summary of manifest.pages ?? []) {
    if (!summary?.specPath) continue;
    const file = resolve(dir, summary.specPath);
    if (existsSync(file)) pages.push({ path: summary.specPath, spec: readJson(file) });
  }
  const etags = { 'comix.manifest.json': etagOfFile(manifestPath) };
  for (const page of pages) etags[page.path] = etagOfFile(resolve(dir, page.path));
  return { slug, manifest, pages, etags };
}

export function renderComixCatalogTs(comixes) {
  const manifests = comixes.map((c) => c.manifest);
  const pagesBy = {};
  for (const c of comixes) {
    const specs = c.pages.map((p) => p.spec).sort((a, b) => a.index - b.index);
    if (specs.length > 0) pagesBy[c.slug] = specs;
  }
  const json = (v) => JSON.stringify(v, null, 2);
  return `// AUTO-GENERATED by scripts/harness/generate-comix.mjs — DO NOT EDIT BY HAND.
import type { ComixManifest, ComixPageSpec } from '../spec-types.js';

export const GENERATED_COMIX_MANIFESTS: ComixManifest[] = ${json(manifests)};

export const GENERATED_COMIX_PAGES_BY_ID: Record<string, ComixPageSpec[]> = ${json(pagesBy)};
`;
}

export function compileAllComix() {
  const comixes = listComixIds().map(readComix);
  return { comixes, ts: renderComixCatalogTs(comixes) };
}

/** Writes `src/cinematic/generated/catalog-data.ts` only when it changed. Returns whether it did. */
export function writeComixCatalog(ts) {
  const existing = existsSync(comixCatalogFile) ? readFileSync(comixCatalogFile, 'utf8') : '';
  if (existing === ts) return false;
  mkdirSync(dirname(comixCatalogFile), { recursive: true });
  writeFileSync(comixCatalogFile, ts);
  return true;
}
