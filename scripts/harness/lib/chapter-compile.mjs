// Reads chapters/<slug>/ from disk and renders src/chapters/generated/catalog-data.ts.
// Shared by `generate-chapter.mjs` (CLI) and the chapter editor's dev API, so both compile identically.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { projectRoot } from './load.mjs';

export const chaptersDir = resolve(projectRoot, 'chapters');
export const catalogFile = resolve(projectRoot, 'src/chapters/generated/catalog-data.ts');

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));

/** Content hash of a file's text: the editor sends it back on save so a write never overwrites a newer file. */
export const etagOf = (text) => createHash('sha1').update(text).digest('hex');
export const etagOfFile = (path) => (existsSync(path) ? etagOf(readFileSync(path, 'utf8')) : '');

export function listChapterSlugs() {
  return readdirSync(chaptersDir)
    .filter((d) => statSync(resolve(chaptersDir, d)).isDirectory() && existsSync(resolve(chaptersDir, d, 'chapter.manifest.json')))
    .sort();
}

/**
 * One chapter as the editor and the compiler see it. Paths are relative to the chapter folder.
 * `levels[i].path` is the spec path declared by `manifest.levels[i].specPath`.
 * `etags` maps each of those paths (and `chapter.manifest.json`) to a hash of the file as it is on disk now.
 */
export function readChapter(slug) {
  const dir = resolve(chaptersDir, slug);
  const manifest = readJson(resolve(dir, 'chapter.manifest.json'));
  const levels = [];
  for (const summary of manifest.levels ?? []) {
    if (!summary.specPath) continue;
    const file = resolve(dir, summary.specPath);
    if (existsSync(file)) levels.push({ path: summary.specPath, spec: readJson(file) });
  }
  const comixPath = manifest.comix?.specPath;
  const dialogsPath = manifest.comix?.dialogsPath;
  const comix = comixPath && existsSync(resolve(dir, comixPath)) ? readJson(resolve(dir, comixPath)) : undefined;
  const dialogs = dialogsPath && existsSync(resolve(dir, dialogsPath)) ? readJson(resolve(dir, dialogsPath)) : undefined;
  const pagesDir = resolve(projectRoot, 'public/comix', manifest.id);
  const comixPages = existsSync(pagesDir) ? readdirSync(pagesDir).filter((f) => /^page-\d+\.png$/.test(f)).sort() : [];
  const etags = { 'chapter.manifest.json': etagOfFile(resolve(dir, 'chapter.manifest.json')) };
  for (const rel of [...levels.map((l) => l.path), comixPath, dialogsPath]) {
    if (rel) etags[rel] = etagOfFile(resolve(dir, rel));
  }
  return { slug, manifest, levels, comix, comixPath, dialogs, dialogsPath, comixPages, etags };
}

export function renderCatalogTs(chapters) {
  const manifests = chapters.map((c) => c.manifest).sort((a, b) => a.issueNumber - b.issueNumber);
  const levelsBy = {};
  const comixBy = {};
  const dialogsBy = {};
  for (const c of chapters) {
    const specs = c.levels.map((l) => l.spec).sort((a, b) => a.index - b.index);
    if (specs.length > 0) levelsBy[c.slug] = specs;
    if (c.comix) comixBy[c.slug] = c.comix;
    if (c.dialogs) dialogsBy[c.slug] = c.dialogs;
  }
  const json = (v) => JSON.stringify(v, null, 2);
  return `// AUTO-GENERATED by scripts/harness/generate-chapter.mjs — DO NOT EDIT BY HAND.
import type { ChapterDialogs, ChapterManifest, ComixStorySpec, LevelSpec } from '../types.js';

export const GENERATED_MANIFESTS: ChapterManifest[] = ${json(manifests)};

export const GENERATED_LEVELS_BY_CHAPTER: Record<string, LevelSpec[]> = ${json(levelsBy)};

export const GENERATED_COMIX_BY_CHAPTER: Record<string, ComixStorySpec> = ${json(comixBy)};

export const GENERATED_DIALOGS_BY_CHAPTER: Record<string, ChapterDialogs> = ${json(dialogsBy)};
`;
}

export function compileAll() {
  const chapters = listChapterSlugs().map(readChapter);
  return { chapters, ts: renderCatalogTs(chapters) };
}

/** Writes the catalog only when it changed. Returns whether it did. */
export function writeCatalog(ts) {
  const existing = existsSync(catalogFile) ? readFileSync(catalogFile, 'utf8') : '';
  if (existing === ts) return false;
  mkdirSync(dirname(catalogFile), { recursive: true });
  writeFileSync(catalogFile, ts);
  return true;
}
